    fun guide(symbol: String): List<List<Offset>>? = paths[symbol]?.split('|')?.map { stroke -> stroke.split(' ').map { point -> val xy = point.split(','); Offset(xy[0].toFloat() / 100, xy[1].toFloat() / 100) } }
    fun matches(input: List<Offset>, guide: List<Offset>): Boolean {
        if (input.size < 3 || guide.size < 2) return false
        val tolerance = .12f
        if ((input.first() - guide.first()).getDistance() > tolerance || (input.last() - guide.last()).getDistance() > tolerance) return false
        val samples = guide.zipWithNext().flatMap { (a, b) ->
            val steps = ceil((b - a).getDistance() / .025f).toInt().coerceAtLeast(1)
            (0..steps).map { a + (b - a) * (it.toFloat() / steps) }
        }
        var progress = 0
        for (point in input) {
            val window = (progress - 4).coerceAtLeast(0)..(progress + 24).coerceAtMost(samples.lastIndex)
            val nearest = window.minBy { (point - samples[it]).getDistance() }
            if ((point - samples[nearest]).getDistance() > tolerance || nearest < progress - 8) return false
            progress = maxOf(progress, nearest)
        }
        // Coverage rejects shortcuts and touching just the start/end of a long stroke.
        return samples.all { expected -> input.any { (expected - it).getDistance() <= tolerance } }
    }
